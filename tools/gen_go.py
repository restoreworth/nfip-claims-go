"""Generate nfip_gen.go and testdata/ from the nfip-paid-claims-by-state dataset (stdlib only).

  python tools/gen_go.py [path/to/nfip_paid_claims_by_state.json]

Default input: ../nfip-paid-claims-by-state/data/nfip_paid_claims_by_state.json (sibling repository).
The input and the CSV next to it are copied byte for byte to testdata/ so that the Go tests compare every field with them.
"""
import hashlib, json, os, shutil, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
DEFAULT = os.path.join(ROOT, '..', 'nfip-paid-claims-by-state', 'data', 'nfip_paid_claims_by_state.json')
OUT = os.path.join(ROOT, 'nfip_gen.go')
TESTDATA = os.path.join(ROOT, 'testdata', 'nfip_paid_claims_by_state.json')


def gostr(s):
    return json.dumps(s, ensure_ascii=False)  # a JSON string is a valid Go interpreted string literal


def gofloat(x):
    return '0' if x is None else repr(float(x))


def main(src):
    raw = open(src, 'rb').read()
    doc = json.loads(raw)
    src_meta = doc['source']
    recs = doc['records']
    if len(recs) != 51:
        raise SystemExit(f'expected 51 records, got {len(recs)}')
    lines = [
        '// Code generated by tools/gen_go.py from nfip_paid_claims_by_state.json; DO NOT EDIT.',
        '',
        'package nfipclaims',
        '',
        'const (',
        f'\t// AsOfDate is the OpenFEMA asOfDate of the claim records the statistics were computed from.',
        f'\tAsOfDate = {gostr(src_meta["as_of_date"])}',
        f'\t// RetrievedUTC is when the claim records were retrieved from the OpenFEMA API (UTC).',
        f'\tRetrievedUTC = {gostr(src_meta["retrieved_utc"])}',
        f'\t// Endpoint is the OpenFEMA API endpoint the claim records were retrieved from.',
        f'\tEndpoint = {gostr(src_meta["endpoint"])}',
        f'\t// Window is the range of years of loss covered.',
        f'\tWindow = {gostr(doc["method"]["window"])}',
        ')',
        '',
        f'// sourceSHA256 is the SHA-256 of the dataset file this file was generated from.',
        f'const sourceSHA256 = {gostr(hashlib.sha256(raw).hexdigest())}',
        '',
        'var states = []StateStats{',
    ]
    for r in recs:
        has_x = r['median_excl_top_event'] is not None
        if has_x != (r['event_dependent'] is not None):
            raise SystemExit(f'{r["state"]}: median_excl_top_event and event_dependent disagree on null')
        fields = [
            ('State', gostr(r['state'])), ('Window', gostr(r['window'])), ('AsOfDate', gostr(r['as_of_date'])),
            ('RetrievedUTC', gostr(r['retrieved_utc'])), ('NClaims', str(int(r['n_claims']))),
            ('NPaid', str(int(r['n_paid']))), ('Q1', gofloat(r['q1'])), ('Median', gofloat(r['median'])),
            ('Q3', gofloat(r['q3'])), ('TotalPaid', gofloat(r['total_paid'])),
            ('Median2024USD', gofloat(r['median_2024usd'])), ('TopEvent', gostr(r['top_event'] or '')),
            ('TopEventShare', gofloat(r['top_event_share'])),
            ('MedianExclTopEvent', gofloat(r['median_excl_top_event'])),
            ('HasMedianExclTopEvent', 'true' if has_x else 'false'),
            ('EventDependent', 'true' if r['event_dependent'] else 'false'), ('Status', gostr(r['status'])),
        ]
        lines.append('\t{' + ', '.join(f'{k}: {v}' for k, v in fields) + '},')
    lines += ['}', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    os.makedirs(os.path.dirname(TESTDATA), exist_ok=True)
    shutil.copyfile(src, TESTDATA)
    shutil.copyfile(src[:-len('.json')] + '.csv', TESTDATA[:-len('.json')] + '.csv')
    print('wrote', OUT, 'and', TESTDATA, '-', len(recs), 'records, asOfDate', src_meta['as_of_date'])


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
